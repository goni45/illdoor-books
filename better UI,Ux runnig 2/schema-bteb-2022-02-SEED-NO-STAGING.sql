  ('2022', '68', 'Electronics Technology', '8th Semester', '26881', 'Industrial Attachment & Project Presentation')
),
unique_seed AS (
  SELECT DISTINCT ON (regulation,subject_code)
    regulation,subject_code,subject_name,department,semester
  FROM seed
  ORDER BY regulation,subject_code,technology_code,semester
),
recorded_conflicts AS (
  INSERT INTO public.book_curriculum_seed_conflicts(
    regulation,subject_code,existing_book_id,existing_title,seed_title
  )
  SELECT DISTINCT s.regulation,s.subject_code,b.id,b.title,s.subject_name
  FROM seed s
  JOIN public.books b
    ON b.regulation=s.regulation
   AND lower(regexp_replace(btrim(b.subject_code),'[^a-zA-Z0-9]','','g'))
       =lower(regexp_replace(btrim(s.subject_code),'[^a-zA-Z0-9]','','g'))
  WHERE lower(btrim(b.title))<>lower(btrim(s.subject_name))
  ON CONFLICT DO NOTHING
  RETURNING id
),
inserted_models AS (
  INSERT INTO public.books(
    title,author,subject_code,subject_name,department,semester,status,regulation,migration_key
  )
  SELECT s.subject_name,'BTEB Regulation 2022',s.subject_code,s.subject_name,
         s.department,s.semester,'active',s.regulation,
         'curriculum:'||s.regulation||':'||s.subject_code
  FROM unique_seed s
  WHERE NOT EXISTS (
    SELECT 1 FROM public.books b
    WHERE b.regulation=s.regulation
      AND lower(regexp_replace(btrim(b.subject_code),'[^a-zA-Z0-9]','','g'))
          =lower(regexp_replace(btrim(s.subject_code),'[^a-zA-Z0-9]','','g'))
  )
  ON CONFLICT DO NOTHING
  RETURNING id,regulation,subject_code
),
model_lookup AS (
  SELECT b.id,b.regulation,b.subject_code
  FROM public.books b
  JOIN unique_seed s
    ON b.regulation=s.regulation
   AND lower(regexp_replace(btrim(b.subject_code),'[^a-zA-Z0-9]','','g'))
       =lower(regexp_replace(btrim(s.subject_code),'[^a-zA-Z0-9]','','g'))
  UNION ALL
  SELECT id,regulation,subject_code FROM inserted_models
),
inserted_mappings AS (
  INSERT INTO public.curriculum_entries(book_id,regulation,technology_code,department,semester)
  SELECT m.id,s.regulation,s.technology_code,s.department,s.semester
  FROM seed s
  JOIN model_lookup m
    ON m.regulation=s.regulation
   AND lower(regexp_replace(btrim(m.subject_code),'[^a-zA-Z0-9]','','g'))
       =lower(regexp_replace(btrim(s.subject_code),'[^a-zA-Z0-9]','','g'))
  ON CONFLICT (book_id,regulation,technology_code,semester) DO UPDATE
  SET department=excluded.department
  RETURNING id
)
SELECT
  (SELECT count(*) FROM seed) AS source_mapping_count,
  (SELECT count(*) FROM unique_seed) AS source_unique_model_count,
  (SELECT count(*) FROM inserted_models) AS models_inserted_this_run,
  (SELECT count(*) FROM inserted_mappings) AS mappings_upserted_this_run,
  (SELECT count(*) FROM recorded_conflicts) AS conflicts_recorded_this_run;
